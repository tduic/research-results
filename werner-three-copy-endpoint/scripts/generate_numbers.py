#!/usr/bin/env python3
"""Generate paper/numbers.tex from shipped evidence. No headline number in the
paper is typed by hand: every macro below is read from a shipped data file.

Sources:
  - all_d/exact_t0_v2/cert_manifest.json (certificate bytes, bits, counts)
  - lean/layerD_t0/identity_manifest.json (identity-module family file counts)
  - lean/layerD_t0/identity_modules.txt (module list; its line count must agree)
  - evidence/run2.json (recorded build run: wall time, CPU-hours, peak memory)

Usage: python3 scripts/generate_numbers.py   (writes paper/numbers.tex)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(path):
    with open(os.path.join(ROOT, path)) as f:
        return json.load(f)


def fmt_int(n):
    return f"{n:,}"


def main():
    cert = load("all_d/exact_t0_v2/cert_manifest.json")
    ident = load("lean/layerD_t0/identity_manifest.json")
    run = load("evidence/run2.json")
    stmt = load("evidence/statement-check.json")
    with open(os.path.join(ROOT, "lean/layerD_t0/identity_modules.txt")) as f:
        modules = [ln.strip() for ln in f if ln.strip() and not ln.strip().startswith("#")]
    fam_total = sum(v["files"] for k, v in ident.items() if isinstance(v, dict) and "files" in v)
    # identity_modules.txt lists prep/grid modules too; the manifest family
    # counts are the generated identity-module files. Both totals are checked
    # by the test suite; the paper uses the manifest total for modules.
    assert fam_total == run["modules_total"], (fam_total, run["modules_total"])
    assert run["modules_prep"] + run["modules_light"] + run["modules_heavy"] + run["modules_final"] == run["modules_total"]
    stats = cert["stats"]
    macros = {
        "nmodules": fmt_int(run["modules_total"]),
        "nprep": fmt_int(run["modules_prep"]),
        "nlight": fmt_int(run["modules_light"]),
        "nheavy": fmt_int(run["modules_heavy"]),
        "nfinal": fmt_int(run["modules_final"]),
        "nretries": fmt_int(run["light_retries_killed_for_memory"]),
        "runid": str(run["run_id"]),
        "walltime": run["wall"],
        "cpuhours": run["cpu_hours"],
        "peakmem": run["peak_memory_gb"],
        "peakmod": run["peak_module"].replace("_", r"\_"),
        "nmodulesbefore": fmt_int(run["modules_before_rep_split"]),
        "runstart": run["started_utc"].replace("T", " ").replace("Z", " UTC"),
        "runend": run["finished_utc"].replace("T", " ").replace("Z", " UTC"),
        "maxreldiff": stmt["max_relative_difference"],
        "nblocks": fmt_int(stats["counts"]["blocks"]),
        "nrows": fmt_int(stats["counts"]["rows"]),
        "certbits": f"{stats['bits']['total'] / 1e6:.2f}M",
        "ncpu": str(run["container_cpus"]),
        "containergb": str(run["container_mem_gb"]),
        "certshrunk": f"{cert['v1_stats']['bits']['total'] / stats['bits']['total']:.1f}",
        "vonebits": f"{cert['v1_stats']['bits']['total'] / 1e6:.2f}M",
        "certbytes": fmt_int(stats["bytes"]["total"]),
        "dendelbits": fmt_int(stats["max_bits"]["delta_den"]),
        "vonedendelbits": fmt_int(cert["v1_stats"]["max_bits"]["delta_den"]),
    }
    # Deliberately omitted from the macros (and from the paper): figures that
    # are not in any shipped data file, such as an exact-identity coordinate
    # count or a layer-D contraction total. I do not re-type numbers I cannot
    # recompute from this folder; see AUDIT.md.
    lines = ["% Generated by scripts/generate_numbers.py from shipped evidence.",
             "% Do not edit by hand; regenerate instead."]
    for k, v in macros.items():
        lines.append(r"\newcommand{\%s}{%s}" % (k, v))
    out = os.path.join(ROOT, "paper", "numbers.tex")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(macros)} macros; module list has {len(modules)} lines)")


if __name__ == "__main__":
    main()
