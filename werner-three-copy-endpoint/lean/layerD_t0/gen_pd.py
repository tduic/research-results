#!/usr/bin/env python3
"""Layer D (t = 0): write LayerDT0/Gen/PD/{Den,G<c>,All}.lean — every block multiplier as BlockPD data with a kernel
PD check (checkPDdd on X0 - 2^s mu I with an untrusted short W, and |Delta_i| / DEN <= mu).

Usage: python3 gen_pd.py [OUT_DIR] [--blocks a:b]   (LAYERD_CERT selects the certificate; generated files are git-ignored)
"""
import json, os, sys
import t0data as D

sys.path.insert(0, os.path.join(D.HERE, "..", "layerD_proto"))
os.environ.setdefault("LAYERD_CERT", D.CERT)
import certdata as C  # noqa: E402  (proto: shifted, short_W, dd_ok, dd_params, packed, lean_bigint)

OUT = os.path.join(D.GEN, "PD")
HDR = "/-! Generated by `layerD_t0/gen_pd.py` from the certificate directory; do not edit by hand. -/\n"
BUDGET = float(os.environ.get("LAYERD_PD_BUDGET", "25000"))   # sum k^2.58 per group module


def block_pd(blk):
    A, sh = C.shifted(blk)
    for bits in (32, 48, 64, 96, 128):
        W, E = C.short_W(A, bits)
        if C.dd_ok(E):
            break
    else:
        raise SystemExit("no short W found")
    p = C.dd_params(A, W, E)
    k = p["k"]
    X0 = [[int(v) for v in r] for r in blk["X0"]]
    xb = max(abs(v) for r in X0 for v in r).bit_length() + 2
    wbits = p["wb"] + 1
    return dict(k=k, s=int(blk["s"]), mn=int(blk["mu_num"]), me=int(blk["mu_exp"]), xb=xb,
                X0p=[C.packed(r, xb) for r in X0], wbits=wbits, Wp=[C.packed(r, wbits) for r in W],
                beta=p["beta"], wb=p["wb"], ab=p["ab"], eb=p["eb"], delta=[(int(i), int(v)) for i, v in blk.get("delta", [])])


def lean_block(name, q):
    lst = lambda xs: "[" + ",\n    ".join(C.lean_bigint(v) for v in xs) + "]"
    dl = "[" + ", ".join(f"({i}, {C.lean_int(v)})" for i, v in q["delta"]) + "]"
    return (f"def {name} : BlockPD where\n  k := {q['k']}\n  s := {q['s']}\n  mn := {q['mn']}\n  me := {q['me']}\n"
            f"  xb := {q['xb']}\n  X0p := {lst(q['X0p'])}\n  wbits := {q['wbits']}\n  Wp := {lst(q['Wp'])}\n"
            f"  β := {q['beta']}\n  wb := {q['wb']}\n  ab := {q['ab']}\n  eb := {q['eb']}\n  Δ := {dl}\n")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = args[0] if args else OUT
    os.makedirs(out, exist_ok=True)
    rng = None
    if "--blocks" in sys.argv:
        a, b = sys.argv[sys.argv.index("--blocks") + 1].split(":")
        rng = (int(a), int(b))
    blocks = C.load_blocks()
    _, _, den = D.load_multipliers()
    open(os.path.join(out, "Den.lean"), "w").write(
        "import LayerDT0.PDCheck\n" + HDR + f"\nnamespace LayerDT0\n\n/-- The common denominator of the corrections. -/\n"
        f"def DEN : Nat := {den}\n\nend LayerDT0\n")
    groups, cur, cost = [], [], 0.0
    lo, hi = rng if rng else (0, len(blocks))
    for j in range(lo, hi):
        k = len(blocks[j]["X0"])
        if cur and cost + k ** 2.58 > BUDGET:
            groups.append(cur); cur, cost = [], 0.0
        cur.append(j); cost += k ** 2.58
    if cur:
        groups.append(cur)
    for c, g in enumerate(groups):
        L = ["import LayerDT0.Gen.PD.Den\n", HDR, "\nset_option Elab.async false\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n"]
        for j in g:
            L.append(lean_block(f"pdb{j}", block_pd(blocks[j])))
            L.append(f"theorem pdb{j}_ok : pdChk DEN pdb{j} = true := by\n  decide +kernel\n")
        L.append(f"def pdGrp{c} : List BlockPD := [" + ", ".join(f"pdb{j}" for j in g) + "]\n")
        L.append(f"theorem pdGrp{c}_ok : pdGrp{c}.all (pdChk DEN) = true := by\n"
                 f"  simp only [pdGrp{c}, List.all_cons, List.all_nil, " + ", ".join(f"pdb{j}_ok" for j in g) + ", Bool.and_self]\n")
        L.append("end LayerDT0\n")
        open(os.path.join(out, f"G{c}.lean"), "w").write("\n".join(L))
    L = ["import LayerDT0.PD\n" + "".join(f"import LayerDT0.Gen.PD.G{c}\n" for c in range(len(groups))), HDR,
         "\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n",
         "/-- All block multipliers, in `blocks.jsonl` order. -/\ndef allPD : List BlockPD :=\n  " +
         " ++ ".join(f"pdGrp{c}" for c in range(len(groups))) + "\n",
         "theorem allPD_ok : allPD.all (pdChk DEN) = true := by\n  simp only [allPD, List.all_append, " +
         ", ".join(f"pdGrp{c}_ok" for c in range(len(groups))) + ", Bool.and_self]\n",
         f"theorem allPD_length : allPD.length = {hi - lo} := by\n  rfl\n",
         "/-- **Layer D obligation 5:** every block multiplier is positive definite. -/\n"
         "theorem pd_all (j : ℕ) (hj : j < allPD.length) : ((allPD.getD j default).X DEN).PosDef :=\n"
         "  BlockPD.X_posDef (pdChk_getD allPD_ok hj)\n",
         "end LayerDT0\n\n#print axioms LayerDT0.pd_all\n"]
    open(os.path.join(out, "All.lean"), "w").write("\n".join(L))
    json.dump(groups, open(os.path.join(out, "groups.json"), "w"))
    print(f"wrote {out}: {len(groups)} group modules")


if __name__ == "__main__":
    main()
