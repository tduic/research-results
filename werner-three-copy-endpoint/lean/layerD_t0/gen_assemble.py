#!/usr/bin/env python3
"""Layer D (t = 0): write LayerDT0/Gen/{Cuts,Lam,AllBC,LamOk,Endpoint,IdentityParts}.lean and LayerDT0/Gen/Blocks/G<c>.lean.

The block codes reuse the PD grouping (Gen/PD/groups.json; run gen_pd.py first).  Usage: python3 gen_assemble.py
"""
import json, math, os, sys
from fractions import Fraction
import t0data as D

sys.path.insert(0, os.path.join(D.HERE, "..", "layerD_proto"))
os.environ.setdefault("LAYERD_CERT", D.CERT)
import certdata as C  # noqa: E402

GEN = D.GEN
HDR = "/-! Generated by `layerD_t0/gen_assemble.py` from the certificate directory; do not edit by hand. -/\n"
ISCUT_ORDER = [(), (0,), (2,), (3,), (0, 1), (0, 2), (2, 3)]   # the disjuncts of WernerEndpoint.IsCut
CUT_IX = {T: i for i, (T, _, _) in enumerate(D.CUTS)}
FAM = {"31": ".f31", "22": ".f22", "13": ".f13"}


def iscut_proof(T):
    p = ISCUT_ORDER.index(T)
    term = "rfl"
    if p < 6:
        term = f"Or.inl rfl"
    for _ in range(p):
        term = f"Or.inr ({term})"
    return term


def gen_cuts(sites, qub):
    L = ["import LayerDT0.Assemble\nimport LayerDT0.Gen.Qubit\n" + "".join(f"import LayerDT0.Gen.Sites{n}\n" for _, _, n in D.CUTS),
         HDR, "\nnamespace LayerDT0\n\nopen WernerEndpoint\n"]
    for T, lean, n in D.CUTS:
        qs = [f"qd_{n}_{m}" for m in range(len(qub[T]))]
        for m, Q in enumerate(qub[T]):
            L.append(f"def qd_{n}_{m} : QubData := ⟨{Q['k']}, qJl_{n}_{m}, qFl_{n}_{m}⟩\n")
        ss = [f"sd_{n}_{r}" for r in range(len(sites[T]))]
        L.append(f"/-- Cut `{lean}`. -/\ndef cut_{n} : CutData := ⟨{lean}, tab_{n}, [{', '.join(ss)}], [{', '.join(qs)}]⟩\n")
        tab = f"tabAt_{n} d" if n == "E" else f"tabAt_{n} (by omega)"
        L.append(f"theorem good_{n} : cut_{n}.Good := by\n"
                 f"  refine ⟨{iscut_proof(T)}, fun d hd => {tab}, fun s hs => ?_, fun q hq => ?_⟩\n"
                 f"  · simp only [cut_{n}, List.mem_cons, List.not_mem_nil, or_false] at hs\n"
                 f"    rcases hs with {' | '.join(['rfl'] * len(ss))}\n"
                 f"    exacts [{', '.join('siteCert_' + x[3:] for x in ss)}]\n"
                 f"  · simp only [cut_{n}, List.mem_cons, List.not_mem_nil, or_false] at hq\n"
                 f"    rcases hq with {' | '.join(['rfl'] * len(qs))}\n"
                 f"    exacts [{', '.join('qubitAt_' + x[3:] for x in qs)}]\n")
    names = [n for _, _, n in D.CUTS]
    alts = lambda f: "".join(f"  | {i} => {f(nm)}\n" for i, nm in enumerate(names)) + f"  | _ => {f(names[0])}\n"
    L.append("def cuts : ℕ → CutData\n" + alts(lambda nm: f"cut_{nm}"))
    L.append("def cutT : ℕ → Finset (Fin 4)\n" + alts(lambda nm: f"cut_{nm}.T"))
    L.append("def cutNS : ℕ → ℕ\n" + alts(lambda nm: f"cut_{nm}.sites.length"))
    L.append("def cutNQ : ℕ → ℕ\n" + alts(lambda nm: f"cut_{nm}.qubs.length"))
    for nm, rhs in (("T", "cutT c"), ("NS", "cutNS c"), ("NQ", "cutNQ c")):
        fld = {"T": "T", "NS": "sites.length", "NQ": "qubs.length"}[nm]
        L.append(f"theorem cuts_{nm} : ∀ c, (cuts c).{fld} = {rhs} := by\n  intro c\n  match c with\n"
                 + "".join(f"  | {i} => rfl\n" for i in range(7)) + "  | _ + 7 => rfl\n")
    L.append("theorem cuts_good : ∀ c, (cuts c).Good := by\n  intro c\n  match c with\n"
             + "".join(f"  | {i} => exact good_{nm}\n" for i, nm in enumerate(names)) + "  | _ + 7 => exact good_E\n")
    L.append("end LayerDT0\n\n#print axioms LayerDT0.cuts_good\n")
    return "\n".join(L)


def kind_of(spec):
    if spec == "c3":
        return ".c3", CUT_IX[(3,)]
    if spec == "c23":
        return ".c23", CUT_IX[(2, 3)]
    fam, T = spec[1:3], D.parse_cut(spec[3:])
    return f"(.word {FAM[fam]} {D.CUT_LEAN[T]})", CUT_IX[T]


def gen_block(j, blk):
    kind, cut = kind_of(blk["spec"])
    parts = [blk["B"], []] if "B" in blk else [blk["Bu"], blk["Bv"]]
    rows = [[int(v) for v in r] for P in parts for r in P]
    ncol = len(rows[0])
    bb = max(abs(v) for r in rows for v in r).bit_length() + 2
    pk = lambda P: "[" + ", ".join(C.lean_bigint(C.packed([int(v) for v in r], bb)) for r in P) + "]"
    return (f"def bc{j} : BCode where\n  kind := {kind}\n  cut := {cut}\n  rs := {list(blk['rs'])}\n  rq := {blk['rq']}\n"
            f"  bb := {bb}\n  ncol := {ncol}\n  Bp := {pk(parts[0])}\n  Bvp := {pk(parts[1])}\n")


def main():
    sites, _ = D.load_sites()
    qub = D.load_qubit()
    open(os.path.join(GEN, "Cuts.lean"), "w").write(gen_cuts(sites, qub))
    groups = json.load(open(os.path.join(GEN, "PD", "groups.json")))
    blocks = C.load_blocks()
    os.makedirs(os.path.join(GEN, "Blocks"), exist_ok=True)
    for c, g in enumerate(groups):
        L = ["import LayerDT0.Assemble\n", HDR, "\nnamespace LayerDT0\n\nopen WernerEndpoint\n"]
        L += [gen_block(j, blocks[j]) for j in g]
        L.append(f"def bcGrp{c} : List BCode := [" + ", ".join(f"bc{j}" for j in g) + "]\n\nend LayerDT0\n")
        open(os.path.join(GEN, "Blocks", f"G{c}.lean"), "w").write("\n".join(L))
    rows_sel, lam, _ = D.load_multipliers()
    den = 1
    for x in lam:
        den = den * x.denominator // math.gcd(den, x.denominator)
    num = [int(x * den) for x in lam]
    open(os.path.join(GEN, "Lam.lean"), "w").write(
        "import LayerDT0.Assemble\n" + HDR + "\nnamespace LayerDT0\n\n/-- The row multipliers' numerators over `lamDen`. -/\n"
        "def lamNum : List ℤ := [" + ", ".join(C.lean_int(v) for v in num) + f"]\n\ndef lamDen : ℕ := {den}\n\nend LayerDT0\n")
    nb, ng, nr = sum(len(g) for g in groups), len(groups), len(rows_sel)
    # the kernel checks allBC_ok and lam_ok in modules of their own (each Lean process <= 3 GB)
    open(os.path.join(GEN, "AllBC.lean"), "w").write("\n".join([
        "import LayerDT0.Gen.Cuts\n" + "".join(f"import LayerDT0.Gen.Blocks.G{c}\n" for c in range(ng)), HDR,
        "\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n",
        "/-- The side conditions of all block codes (`allBC` of `Endpoint.lean` is this concatenation). -/\n"
        "theorem allBC_ok' : (" + " ++ ".join(f"bcGrp{c}" for c in range(ng)) + ").all (BCode.ok cutT cutNS cutNQ) = true := by\n  decide +kernel\n",
        f"theorem allBC_length' : (" + " ++ ".join(f"bcGrp{c}" for c in range(ng)) + f").length = {nb} := by\n  rfl\n",
        "end LayerDT0\n"]))
    open(os.path.join(GEN, "LamOk.lean"), "w").write("\n".join([
        "import LayerDT0.Gen.Lam\nimport LayerDT0.Gen.Rows\n", HDR,
        "\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n",
        f"theorem lam_ok : lamOK rowCodes lamNum {nr} = true := by\n  decide +kernel\n",
        "end LayerDT0\n"]))
    L = ["import LayerDT0.Gen.Cuts\nimport LayerDT0.Gen.AllBC\nimport LayerDT0.Gen.LamOk\nimport LayerDT0.Gen.PD.All\n", HDR,
         "\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n",
         "/-- All block codes, in `blocks.jsonl` order. -/\ndef allBC : List BCode :=\n  " + " ++ ".join(f"bcGrp{c}" for c in range(ng)) + "\n",
         "theorem allBC_ok : allBC.all (BCode.ok cutT cutNS cutNQ) = true := allBC_ok'\n",
         f"theorem allBC_length : allBC.length = {nb} := allBC_length'\n",
         "/-- **The remaining obligation (layer D item 7):** the certificate's identity\n"
         "`obj(μ) = ∑_b ⟨X_b, L_b(μ)⟩ + ∑_r λ_r row_r(μ)` for every orbit-invariant trace-coordinate vector `μ`,\n"
         "for the explicit blocks, multipliers, rows and `λ` of the certificate. -/\n"
         "def IdentityT0 : Prop :=\n  ∀ μ : Fam → Tup (Fin 3) → ℝ, OrbInv (Fin 3) μ →\n"
         f"    mObj 2 μ = ∑ j : Fin {nb}, ∑ i, ∑ i', (allPD.getD j default).X DEN i i' *\n"
         "        ((allBC.getD j default).toSpec cuts (allPD.getD j default).k).L μ i i' +\n"
         f"      ∑ r : Fin {nr}, lamOf lamNum lamDen r * mRowVal 2 (rowAt rowCodes r).row μ\n",
         "/-- **The three-copy Werner endpoint in every dimension, from the `t = 0` certificate, up to its\n"
         "identity.** All other layer D obligations (tables, site and qubit modules, rows, `λ_trace ≥ 0`,\n"
         "`X_b ≻ 0`) are discharged by kernel checks. -/\n"
         "theorem werner3_endpoint_all_d_of_identityT0 (hid : IdentityT0) :\n"
         "    ∀ (d : ℕ) (C : Matrix (Fin 3 → Fin d) (Fin 3 → Fin d) ℂ), C.rank ≤ 2 → 0 ≤ qfun C :=\n"
         "  fun d C hC => endpoint_of_data cuts cutT cutNS cutNQ cuts_T cuts_NS cuts_NQ cuts_good\n"
         f"    {nb} allBC (fun j hj => all_getD allBC_ok (by rw [allBC_length]; exact hj))\n"
         f"    DEN allPD allPD_ok (by rw [allPD_length]) {nr} rowCodes rowCodes_ok lamNum lamDen lam_ok hid d C hC\n",
         "end LayerDT0\n\n#print axioms LayerDT0.werner3_endpoint_all_d_of_identityT0\n"]
    open(os.path.join(GEN, "Endpoint.lean"), "w").write("\n".join(L))
    # the common scale of hdec: lcm(8, lamDen, 2^{s_b} DEN for every block)
    DEN = D.load_multipliers()[2]
    S = math.lcm(8, den, *[(2 ** int(b["s"])) * DEN for b in blocks])
    # PsT0 as a concatenation of short segments (IdentitySeg.lean): the per-part core checks of the identity modules
    # walk only their own segment (GB blocks, GR rows), not the whole family list
    # block segments: chunks of <= GB blocks inside each PD group (so that bz_eq is structural: zip_append over
    # the groups, then one small rfl per group); identity_parts.segments() is the same layout
    import identity_parts as IPS
    GB, GR = IPS.GB, IPS.GR
    chunks = IPS.block_chunks(groups)
    nbg, nrg = sum(len(c) for c in chunks), (nr + GR - 1) // GR
    bz, gq, g = "", "", 0
    for c, cs in enumerate(chunks):
        names = []
        for ch in cs:
            bz += f"def bzG{g} : List (BCode × BlockPD) := [" + ", ".join(f"(bc{j}, pdb{j})" for j in ch) + "]\n"
            names.append(f"bzG{g}"); g += 1
        gq += (f"theorem bzq{c} : bcGrp{c}.zip pdGrp{c} = " + " ++ ".join(names) + " := rfl\n"
               f"theorem bzl{c} : bcGrp{c}.length = pdGrp{c}.length := rfl\n")
    rz = "".join(f"def rzG{g} : List (RowCode × ℤ) := ((rowCodes.zip lamNum).drop {g * GR}).take {GR}\n" for g in range(nrg))
    segs = (["segO idS f"] + [f"segB cuts DEN idS f bzG{g}" for g in range(nbg)] +
            [f"segR idS lamDen f rzG{g}" for g in range(nrg)])
    open(os.path.join(GEN, "IdentityParts.lean"), "w").write("\n".join([
        "import LayerDT0.Gen.Endpoint\nimport LayerDT0.IdentitySeg\n", HDR,
        "\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint LayerDProto\n",
        "/-- The common scale `S = lcm(8, lamDen, 2^{s_b} DEN)` of `hdec`. -/\n"
        f"def idS : ℕ := {S}\n",
        f"theorem idS_ok : scaleOK DEN lamDen idS {nb} allPD = true := by\n  decide +kernel\n",
        "theorem idS_pos : 0 < idS := by\n  decide +kernel\n",
        f"/-- The blocks in groups of {GB} (`blocks.jsonl` order). -/\n" + bz,
        f"/-- The rows in groups of {GR} (row order). -/\n" + rz,
        gq + "theorem bz_eq : allBC.zip allPD = " + " ++ ".join(f"bzG{g}" for g in range(nbg)) + " := by\n"
        "  simp only [allBC, allPD, List.zip_append, List.length_append, " + ", ".join(f"bzl{c}" for c in range(ng)) + "]\n"
        "  simp only [" + ", ".join(f"bzq{c}" for c in range(ng)) + ", List.append_assoc]\n",
        "theorem rz_eq : rowCodes.zip lamNum = " + " ++ ".join(f"rzG{g}" for g in range(nrg)) + " := rfl\n",
        f"theorem rowCodes_length : rowCodes.length = {nr} := rfl\n",
        f"theorem lamNum_length : lamNum.length = {nr} := rfl\n",
        "/-- **The part list of family `f`**: `psOf (allParts …) f` (objective, blocks, rows; `IdentityDec.allParts`)\n"
        "written as a concatenation of segments (`PsT0_eq`). -/\n"
        "def PsT0 (f : Fam) : List PartData :=\n  " + " ++\n    ".join(segs) + "\n",
        "theorem PsT0_eq (f : Fam) :\n"
        f"    psOf (allParts cuts DEN idS {nb} allBC allPD {nr} rowCodes lamNum lamDen) f = PsT0 f := by\n"
        f"  rw [psOf_allParts_seg cuts DEN idS {nb} allBC allPD {nr} rowCodes lamNum lamDen allBC_length allPD_length\n"
        "    rowCodes_length lamNum_length _ _ bz_eq rz_eq f]\n"
        "  simp only [PsT0, segB_append, segR_append, List.append_assoc]\n",
        "/-- **`IdentityT0` from the three family zeros** (`hdec_of_data` and `identity_of_decomp`). -/\n"
        "theorem identityT0_of_famZero (hz : ∀ f, FamZero f (PsT0 f)) : IdentityT0 := by\n"
        "  unfold IdentityT0\n  intro μ hμ\n"
        f"  exact identity_of_parts cuts DEN idS {nb} allBC allPD allPD_ok (by rw [allPD_length]) {nr} rowCodes lamNum\n"
        "    lamDen idS_ok idS_pos (fun f => by rw [PsT0_eq]; exact hz f) μ hμ\n",
        "end LayerDT0\n\n#print axioms LayerDT0.PsT0_eq\n#print axioms LayerDT0.identityT0_of_famZero\n"]))
    print("wrote", GEN)


if __name__ == "__main__":
    main()
