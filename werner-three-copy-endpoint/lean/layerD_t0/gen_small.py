#!/usr/bin/env python3
"""Layer D (t = 0): write the small generated modules LayerDT0/Gen/{Tables,Qubit}.lean from a certificate directory.

Usage: python3 gen_small.py [OUT_DIR]   (default: LayerDT0/Gen next to this file; LAYERD_CERT selects the certificate)
"""
import os, sys
import t0data as D

OUT = sys.argv[1] if len(sys.argv) > 1 else D.GEN
HDR = "/-! Generated by `layerD_t0/gen_small.py` from the certificate directory; do not edit by hand. -/\n"

# relabellings (as in LayerC_Walled.closure_index): T' <- T via pi; Lean name of pi
RELABEL = {(0,): ((3,), (3, 1, 2, 0), "(Equiv.swap 0 3)"), (2,): ((3,), (0, 1, 3, 2), "(Equiv.swap 2 3)"),
           (0, 2): ((2, 3), (3, 1, 2, 0), "(Equiv.swap 0 3)"), (0, 1): ((2, 3), (2, 3, 0, 1), "swap0213")}


def conj_index(pi):
    return [D.IDX[D.comp(D.comp(pi, p), D.inv(pi))] for p in D.PERMS]


def fin_vec(v):
    return "![" + ", ".join(str(x) for x in v) + "]"


def rowsplit(name, var, prop, n=24):
    """`theorem name : ∀ var : Fin n, prop` from one kernel check per row (bounded kernel memory)."""
    out = []
    for k in range(n):
        out.append(f"theorem {name}_{k} : {prop.replace(var + ' ', f'({k} : Fin {n}) ').replace(var + ')', f'({k} : Fin {n}))')} := by\n  decide +kernel\n")
    out.append(f"theorem {name} : ∀ {var} : Fin {n}, {prop} := by\n  intro {var}; fin_cases {var}\n  exacts [" +
               ", ".join(f"{name}_{k}" for k in range(n)) + "]\n")
    return "\n".join(out)


def gen_tables(tabs):
    L = ["import LayerDT0.Tables\n", HDR, "\nset_option Elab.async false\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n"]
    for T, lean, name in D.CUTS:
        S, Lt = tabs[T]
        L.append(f"/-- The verifier's literal table, cut `{lean}`: product indices. -/\n"
                 f"def tabS_{name} : List (List ℕ) := {D.lean_list(S)}\n")
        L.append(f"/-- The verifier's literal table, cut `{lean}`: loop exponents. -/\n"
                 f"def tabL_{name} : List (List ℕ) := {D.lean_list(Lt)}\n")
        L.append(f"/-- The block table of cut `{lean}`. -/\nabbrev tab_{name} : P4 → P4 → P4 × ℕ := tabOf tabS_{name} tabL_{name}\n")
    # T = {} : group multiplication
    L.append(rowsplit("te_E", "i", "∀ j : Fin 24, (∀ x, permFun (tS tabS_E i j) x = permFun i (permFun j x)) ∧ n2 tabL_E i j = 0"))
    L.append("theorem tabAt_E (d : ℕ) : TabAt ∅ d tab_E :=\n  tabAt_empty te_E d\n")
    for T, rows in (((3,), "T3"), ((2, 3), "T23")):
        L.append(rowsplit(f"tc_{rows}", "i", f"tabCertRow certRow{rows} tabS_{rows} tabL_{rows} i = true"))
        L.append(f"theorem tabAt_{rows} {{d : ℕ}} (hd : 1 ≤ d) : TabAt {D.CUT_LEAN[T]} d tab_{rows} :=\n"
                 f"  tabAt_of_cert muC_{rows} chk{rows} tc_{rows} hd\n")
    for T2, (T, pi, pilean) in RELABEL.items():
        n2, n = D.CUT_NAME[T2], D.CUT_NAME[T]
        ci = conj_index(pi)
        S, Lt = tabs[T]
        S2, L2 = tabs[T2]
        for i in range(24):
            for j in range(24):
                assert S2[ci[i]][ci[j]] == ci[S[i][j]] and L2[ci[i]][ci[j]] == Lt[i][j], (T2, i, j)
        L.append(f"/-- Index map of the relabelling `{D.CUT_LEAN[T]}` → `{D.CUT_LEAN[T2]}`. -/\n"
                 f"def ci_{n2} : Fin 24 → Fin 24 := {fin_vec(ci)}\n")
        L.append(f"theorem rel_{n2} : ∀ i : Fin 24, ∀ q, Equiv.sumCongr {pilean} {pilean}\n"
                 f"    (muT {D.CUT_LEAN[T]} i ((Equiv.sumCongr {pilean} {pilean}).symm q)) = muT {D.CUT_LEAN[T2]} (ci_{n2} i) q := by\n"
                 f"  decide +kernel\n")
        L.append(rowsplit(f"ct_{n2}", "i", f"∀ j : Fin 24, tS tabS_{n2} (ci_{n2} i) (ci_{n2} j) = ci_{n2} (tS tabS_{n} i j) ∧ "
                          f"n2 tabL_{n2} (ci_{n2} i) (ci_{n2} j) = n2 tabL_{n} i j"))
        L.append(f"theorem tabAt_{n2} {{d : ℕ}} (hd : 1 ≤ d) : TabAt {D.CUT_LEAN[T2]} d tab_{n2} :=\n"
                 f"  tabAt_relabel {pilean} ci_{n2} rel_{n2} (by decide) ct_{n2} (tabAt_{n} hd)\n")
    L.append("end LayerDT0\n")
    for _, _, name in D.CUTS:
        L.append(f"#print axioms LayerDT0.tabAt_{name}\n")
    return "\n".join(L)


def gen_qubit(qub):
    L = ["import LayerDT0.Basic\n", HDR, "\nset_option Elab.async false\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n"]
    names = []
    for T, lean, name in D.CUTS:
        for m, Q in enumerate(qub[T]):
            nm = f"{name}_{m}"
            L.append(f"/-- Qubit module {m} of cut `{lean}` (`k_q = {Q['k']}`): `J`, 16 rows. -/\n"
                     f"def qJl_{nm} : List (List ℤ) := {D.lean_list(Q['J'])}\n")
            L.append(f"/-- `Fq(p) = Jᵀ Γ_T(P_p) J` (= the verifier's `E_q = G π`). -/\n"
                     f"def qFl_{nm} : List (List (List ℤ)) := {D.lean_list(Q['F'])}\n")
            L.append(f"theorem qubitAt_{nm} : QubitAt {lean} (qF {Q['k']} qFl_{nm}) (qJ {Q['k']} qJl_{nm}) :=\n"
                     f"  qubitAt_of_chk (by decide +kernel)\n")
            names.append(nm)
    L.append("end LayerDT0\n")
    for nm in names:
        L.append(f"#print axioms LayerDT0.qubitAt_{nm}\n")
    return "\n".join(L)


def gen_rows():
    rows_sel, lam, _ = D.load_multipliers()
    _, codes = D.rowdef()
    n = len(rows_sel)
    L = ["import LayerDT0.Rows\n", HDR, "\nset_option Elab.async false\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n"]
    L.append(f"/-- The certificate's {n} selected rows (`multipliers.json` `rows`, as `ROWDEF` codes). -/\n"
             f"def rowCodes : List RowCode :=\n  [" + ",\n    ".join(D.lean_rowcode(codes[i]) for i in rows_sel) + "]\n")
    L.append(f"def rowCode (r : Fin {n}) : RowCode := rowAt rowCodes r\n")
    L.append(f"theorem rowCodes_ok : rowCodes.all RowCode.ok = true := by\n  decide +kernel\n")
    L.append(f"theorem rowCode_ok (r : Fin {n}) : (rowCode r).ok = true := rowAt_ok rowCodes_ok r\n")
    L.append(f"/-- **Layer D obligation 6 (rows):** every selected row is physically valid. -/\n"
             f"theorem rowValid_all : ∀ r : Fin {n}, RowValid (Fin 3) (rowCode r).row (rowCode r).val :=\n"
             f"  fun r => (rowCode r).valid (rowCode_ok r)\n")
    L.append("end LayerDT0\n\n#print axioms LayerDT0.rowValid_all\n")
    return "\n".join(L)


def main():
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "Tables.lean"), "w").write(gen_tables(D.tables()))
    open(os.path.join(OUT, "Qubit.lean"), "w").write(gen_qubit(D.load_qubit()))
    open(os.path.join(OUT, "Rows.lean"), "w").write(gen_rows())
    print("wrote", OUT)


if __name__ == "__main__":
    main()
