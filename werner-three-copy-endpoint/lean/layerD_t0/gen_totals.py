#!/usr/bin/env python3
"""Layer D (t = 0): the literal-free family totals of IdentityT0 (step 2 of the README's next steps).

For one family f and a list of parts it writes, under LayerDT0/Gen/Id/F<f>/ (git-ignored):

  Pos.lean   the reduced grid positions pos<d> (one grid point per H-orbit; 1,142 / 2,391 / 1,142 in all)
  Orb.lean   `posok<d>` and the orbit witnesses, packed and checked in slices (`orb<d>_<k> : witSlice ... = true`),
             (core Lean only); Fam.lean derives `cov<d>`: every grid point is H-equivalent to a reduced one
  P<i>.lean  one module per part: `P<i> : PartData`, `pstat<i>` (fold checks, closure of K), and per grid value d
             the coset data `Q<i>d<d>` and one theorem per chunk
               ch<i>d<d>c<c> : partDR beta ... d S1 G pos<d> = some L
             where L packs the chunk's digits at the reduced positions only (|pos<d>| digits, not 24*24*|S1|)
  K.lean     the family checks `famz<d> : familyZeroOK beta (Ps.zip Qs<d>) = true` (packed sum of the claims is 0)
  Fam.lean   `famZero : FamZero .f<f> Ps` via `family_at_d_zeroR` (R2Reduced.lean) and `famZero_of_grid`

and appends the modules, in build order, to the module list read by run_identity.sh (one Lean module per line,
`#` comments; part modules first, then K and Fam).

The parts.  `--parts blocks` (default) takes the route-2' block parts of the certificate (word blocks of family f
and the f-part of every coupled block) with X = X0 (the prototype's convention, as gen_asm.py).  The identity
needs step 1's parts `Ps f` (scaled X, rows, objective; see the INTERFACE section of README.md): step 1 supplies
them as `identity_parts.parts(fam)` (a list of gen_asm part dicts: ks, X, Bl, Br, fac, tabs, mods, name), which
`--parts step1` imports.  FamZero holds only for the complete family, so `--parts blocks` writes the part
modules and K.lean but not Fam.lean unless the family total vanishes (as in `--negate`, the plumbing test that
pairs every part with its negation).

Usage:
  LAYERD_CERT=<cert> python3 layerD_t0/gen_totals.py FAM [--blocks all|B,B,...] [--parts blocks|step1]
      [--negate] [--budget UNITS] [--list layerD_t0/identity_modules.txt] [--measure-only]
--measure-only computes everything but writes no part, K or Fam module (only sizes are reported).  Prints a JSON
summary (source bytes; full_lit_bytes_est is what the chunk claims would be on the full grid).
"""
import argparse, json, os, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "layerD_proto"))
sys.set_int_max_str_digits(0)

import numpy as np  # noqa: E402
import route2  # noqa: E402
import reduced  # noqa: E402
import gen_asm  # noqa: E402
import recompress  # noqa: E402
from certdata import load_blocks, load_modules, lean_bigint  # noqa: E402
from gen_identity import rho_tables, coupled_maps, lean_mat, pack_signed  # noqa: E402

GEN = os.environ.get("LAYERD_T0_GEN", os.path.join(HERE, "LayerDT0", "Gen"))
LEAN_FAM = {"31": ".f31", "13": ".f13", "22": ".f22"}
BOSN = {"31": "bosN31", "13": "bosN31", "22": "bosN22"}
HB = {"31": "bosN31_f31", "13": "bosN31_f13", "22": "bosN22_f22"}
HC = {"31": "bosN31_comp31", "13": "bosN31_comp13", "22": "bosN22_comp22"}
HN = {"31": "hcodes31_nodup", "13": "hcodes31_nodup", "22": "hcodes22_nodup"}
DCF = {"31": "dc31", "13": "dc31", "22": "dc22"}
S1F = {"31": "s1_31", "13": "s1_31", "22": "s1_22"}
BOSF = {"31": "bos31L", "13": "bos31L", "22": "bos22L"}
MEMF = {"31": "bos31L_mem", "13": "bos13L_mem", "22": "bos22L_mem"}
MEETS = {"31": "meetsR_31", "13": "meetsR_31", "22": "meetsR_22"}



def stable_cmd(argv):
    """the generator arguments for the GENERATED header, without --list PATH and --reuse (which do not change
    the generated Lean), so regenerating does not change unchanged files and Lake keeps their builds"""
    out, skip = [], False
    for x in argv:
        if skip:
            skip = False
            continue
        if x == "--list":
            skip = True
            continue
        if x.startswith("--list=") or x == "--reuse":
            continue
        out.append(x)
    return " ".join(out)

def hdr(ns, imports, cmd, opens="LayerDProto"):
    return (f"-- GENERATED by layerD_t0/gen_totals.py {cmd}. Do not edit.\n"
            + "".join(f"import {m}\n" for m in imports) +
            "set_option maxHeartbeats 0\nset_option maxRecDepth 100000\nset_option Elab.async false\n\n"
            f"namespace {ns}\nopen {opens}\n"
            "set_option profiler true\nset_option profiler.threshold 200\n")


def block_part_list(blocks, fam, sel):
    """(block, part) pairs of family fam: word blocks (part 0) and the fam-part of every coupled block"""
    out = []
    for bi in sel:
        si = route2.spec_info(blocks[bi]["spec"])
        if si["kind"] == "word":
            if si["fam"] == fam:
                out.append((bi, 0))
        else:
            out.append((bi, {"31": 0, "13": 1, "22": 2}[fam]))
    return out


def scaled_X(blk, smax, den):
    """X0 2^(s_max - s) DEN + diag(Delta) 2^(s_max): c X_b for the common scale c = 2^(s_max) DEN"""
    X = [[int(v) * (den << (smax - int(blk["s"]))) for v in r] for r in blk["X0"]]
    for i, v in blk.get("delta", []):
        X[int(i)][int(i)] += int(v) << smax
    return X


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("fam", choices=["31", "22", "13"])
    ap.add_argument("--blocks", default="all")
    ap.add_argument("--parts", default="blocks", choices=["blocks", "step1"])
    ap.add_argument("--negate", action="store_true")
    ap.add_argument("--budget", type=int, default=10 ** 9, help="partD units per chunk (default: one chunk per part and d)")
    ap.add_argument("--list", default=os.path.join(HERE, "identity_modules.txt"))
    ap.add_argument("--measure-only", action="store_true")
    ap.add_argument("--grid-only", action="store_true",
                    help="write only Pos and Orb (they do not depend on the parts) and their module-list lines")
    ap.add_argument("--skip-bad", action="store_true", help="skip parts whose fold data cannot be built (measurement)")
    ap.add_argument("--x", default="x0", choices=["x0", "scaled"],
                    help="x0: X = X0 (prototype); scaled: X = X0 2^(s_max - s) DEN + diag(Delta) 2^(s_max), "
                         "README step 1's common-scale integer X (c = 2^(s_max) DEN)")
    a = ap.parse_args()
    fam = a.fam
    cmd = stable_cmd(sys.argv[1:])
    t0 = time.time()
    blocks = load_blocks()
    if a.grid_only:
        raw = []
    elif a.parts == "step1":
        import identity_parts  # step 1's parts, see README INTERFACE
        raw = identity_parts.parts(fam)
    else:
        RHO = rho_tables(load_modules())
        MAPS = coupled_maps()
        sel = range(len(blocks)) if a.blocks == "all" else [int(x) for x in a.blocks.split(",")]
        bp = block_part_list(blocks, fam, sel)
        raw = [gen_asm.block_part(blocks, RHO, MAPS, bi, pi_) for bi, pi_ in bp]
        if a.x == "scaled":
            from certdata import load_multipliers
            den = int(load_multipliers()["delta_den"])
            smax = max(int(b["s"]) for b in blocks)
            for p, (bi, _) in zip(raw, bp):
                p["X"] = scaled_X(blocks[bi], smax, den)
    # coupled parts: full-rank re-presentation (layerD_proto/recompress.py); P<i> is re-presented, O<i> is the part
    # as given, rel<i> its kernel check, and Fam.lean proves famZeroO : FamZero f Os for the parts as given
    raw = recompress.recompress_all(raw)
    anyrc = any("orig" in p for p in raw)
    if a.negate:
        raw = [q for p in raw for q in (p, dict(p, fac=-p["fac"], name=p["name"] + "neg"))]
    parts, failed = [], []
    for p in raw:
        try:
            q = gen_asm.prepare(p, fam)
        except (ValueError, AssertionError) as ex:  # e.g. fold data for a rank-deficient B (see README)
            if not a.skip_bad:
                raise
            failed.append((p["name"], str(ex)[:80]))
            continue
        q.pop("F0")  # the full tuple tensor (24^4 entries) is only needed for K_b; keep memory flat
        parts.append(q)
    DC, S1 = route2.tree_grid(fam)
    RG = reduced.reduced_grid(fam)
    ats = {d: [gen_asm.at_d(P, fam, d, S1[d], a.budget) for P in parts] for d in DC}
    betas = {}
    for d in DC:
        fb = sum(abs(P["fac"]) * len(P["Ks"]) * len(at["reps"]) * P["fbound"] for P, at in zip(parts, ats[d]))
        betas[d] = (4 * fb).bit_length() + 1
    F = f"F{fam}"
    ns = f"LayerDT0.Gen.Id.{F}"
    mp = f"LayerDT0.Gen.Id.{F}"
    out = os.path.join(GEN, "Id", F)
    os.makedirs(out, exist_ok=True)
    sizes, mods = {}, []

    def write(mod, text):
        with open(os.path.join(out, mod + ".lean"), "w") as fh:
            fh.write(text)
        sizes[mod] = len(text.encode())
        mods.append(f"{mp}.{mod}")

    # reduced positions and orbit checks
    pb = "".join(f"\n/-- reduced positions at t_q = {d}: one per H-orbit, {len(RG[d]['pos'])} of {RG[d]['N']} -/\n"
                 f"def pos{d} : List Nat := {gen_asm.lean_list([str(c) for c in RG[d]['pos']])}\n" for d in DC)
    write("Pos", hdr(ns, ["LayerDProto.R2RedKernel"], cmd) + pb + f"\nend {ns}\n")
    orbs = [reduced.lean_orb(d, RG[d], BOSN[fam]) for d in DC]
    ob = "".join(o for o, _ in orbs)
    write("Orb", hdr(ns, [f"{mp}.Pos"], cmd) + ob + f"\nend {ns}\n")
    # parts
    totals = {d: np.zeros(len(RG[d]["pos"]), dtype=object) for d in DC}
    stats = []
    for i, P in enumerate(parts):
        fds = []
        for fd in P["folds"]:
            fds.append("{ κ := " + gen_asm.lean_k(gen_asm.code(fd["h"])) + ", τ := " + ("true" if fd["tau"] else "false") +
                       ", As := " + gen_asm.lean_list([lean_mat(A) for A in fd["As"]]) +
                       ", Cs := " + gen_asm.lean_list([lean_mat(C) for C in fd["Cs"]]) +
                       ", als := " + gen_asm.lean_list([str(x) if x >= 0 else f"({x})" for x in fd["als"]]) +
                       f", Q := {lean_mat(fd['Q'])}, R := {lean_mat(fd['R'])}, w := {fd['w']} }}")
        rhos = gen_asm.lean_list([gen_asm.lean_list([lean_mat(m) for m in t]) for t in P["tabs"]])
        b = (f"\n-- part {i}: {P['name']} ks={P['ks']} |K_b|={len(P['Ks'])}\n"
             f"def P{i} : PartData :=\n  {{ ks := {P['ks']}, k := {len(P['X'])}, X := {lean_mat(P['X'])},\n"
             f"    Bl := {lean_mat(P['Bl'])}, Br := {lean_mat(P['Br'])}, fac := {lean_bigint(P['fac'])},\n"
             f"    rhos := {rhos},\n    w := {P['w']}, bnd := {P['bnd']},\n"
             f"    folds := {gen_asm.lean_list(fds)},\n    Ks := {gen_asm.lean_list([gen_asm.lean_k(c) for c in P['Ks']])},\n"
             f"    tree := {gen_asm.lean_list([f'({j}, {k_})' for j, k_ in P['tree']])} }}\n"
             f"theorem pstat{i} : partStaticOK {BOSN[fam]} P{i} = true := by decide +kernel\n")
        b += recompress.lean_orig(i, P, lean_mat)
        lit_bytes = 0
        for d in DC:
            at, beta, S1d, pos = ats[d][i], betas[d], S1[d], RG[d]["pos"]
            chs = []
            for ci, ch in enumerate(at["chunks"]):
                gn = f"G{i}d{d}c{ci}"
                b += f"def {gn} : List MGroup := {gen_asm.groups_lean(ch)}\n"
                vals = route2.recipe_exact(P["Y"], P["ks"], P["tabs"], [it[2] for it in ch], fam)[d]
                dig = [int(vals[j]) for j in pos]
                assert all(4 * abs(v) < 2 ** beta for v in dig)
                totals[d] = totals[d] + len(P["Ks"]) * np.array(dig, dtype=object)
                L = pack_signed(dig, beta)
                lit = lean_bigint(L)
                lit_bytes += len(lit)
                chs.append((gn, lit))
            b += (f"def Q{i}d{d} : PartAtD :=\n  {{ reps := {gen_asm.lean_list([gen_asm.lean_k(c) for c in at['reps']])},\n"
                  f"    dec := {gen_asm.lean_list([f'({x}, {y})' for x, y in at['dec']])},\n"
                  f"    chunks := {gen_asm.lean_list([f'({gn}, {lit})' for gn, lit in chs])} }}\n"
                  f"theorem at{i}d{d} : partAtDOK {BOSN[fam]} P{i} Q{i}d{d} = true := by decide +kernel\n")
            for ci, (gn, lit) in enumerate(chs):
                b += (f"theorem ch{i}d{d}c{ci} : partDR {beta} P{i}.w P{i}.bnd P{i}.ks P{i}.k P{i}.X P{i}.Bl P{i}.Br "
                      f"P{i}.fac P{i}.rhos {d} {S1d} {gn} pos{d} = some {lit} := by decide +kernel\n")
            b += (f"theorem hc{i}d{d} : ∀ c ∈ (P{i}, Q{i}d{d}).2.chunks, partDR {beta} (P{i}, Q{i}d{d}).1.w "
                  f"(P{i}, Q{i}d{d}).1.bnd (P{i}, Q{i}d{d}).1.ks (P{i}, Q{i}d{d}).1.k (P{i}, Q{i}d{d}).1.X "
                  f"(P{i}, Q{i}d{d}).1.Bl (P{i}, Q{i}d{d}).1.Br (P{i}, Q{i}d{d}).1.fac (P{i}, Q{i}d{d}).1.rhos "
                  f"{d} {S1d} c.1 pos{d} = some c.2 :=\n  "
                  f"{gen_asm.chain([f'ch{i}d{d}c{ci}' for ci in range(len(chs))])}\n")
        if not a.measure_only:
            write(f"P{i}", hdr(ns, [f"{mp}.Pos"] + ([recompress.KERNEL_IMPORT] if "orig" in P else []), cmd)
                  + b + f"\nend {ns}\n")
        else:
            sizes[f"P{i}"] = len(b.encode())
        stats.append(dict(part=P["name"], ks=P["ks"], K=len(P["Ks"]), reps={d: len(ats[d][i]["reps"]) for d in DC},
                          chunks={d: len(ats[d][i]["chunks"]) for d in DC}, lit_bytes=lit_bytes,
                          full_lit_bytes_est=int(lit_bytes * sum(RG[d]["N"] for d in DC) /
                                                 sum(len(RG[d]["pos"]) for d in DC))))
    zero = all(all(v == 0 for v in totals[d]) for d in DC)
    n = len(parts)
    kb = f"\ndef Ps : List PartData := {gen_asm.lean_list([f'P{i}' for i in range(n)])}\n"
    kb += f"theorem stat : ∀ P ∈ Ps, partStaticOK {BOSN[fam]} P = true :=\n  {gen_asm.chain([f'pstat{i}' for i in range(n)])}\n"
    body = "".join(c for _, c in orbs)  # cov<d>, by witSlice_cover (needs R2Reduced, imported by Fam)
    for d in DC:
        beta, S1d = betas[d], S1[d]
        kb += (f"\ndef Qs{d} : List PartAtD := {gen_asm.lean_list([f'Q{i}d{d}' for i in range(n)])}\n"
               f"theorem hD{d} : ∀ x ∈ Ps.zip Qs{d}, ∀ c ∈ x.2.chunks, partDR {beta} x.1.w x.1.bnd x.1.ks x.1.k "
               f"x.1.X x.1.Bl x.1.Br x.1.fac x.1.rhos {d} {S1d} c.1 pos{d} = some c.2 :=\n  "
               f"{gen_asm.chain([f'hc{i}d{d}' for i in range(n)])}\n"
               f"theorem at{d} : ∀ x ∈ Ps.zip Qs{d}, partAtDOK {BOSN[fam]} x.1 x.2 = true :=\n  "
               f"{gen_asm.chain([f'at{i}d{d}' for i in range(n)])}\n"
               f"theorem stat{d} : ∀ x ∈ Ps.zip Qs{d}, partStaticOK {BOSN[fam]} x.1 = true :=\n"
               f"  fun x hx => stat x.1 (List.of_mem_zip hx).1\n")
        if zero:
            kb += f"theorem famz{d} : familyZeroOK {beta} (Ps.zip Qs{d}) = true := by decide +kernel\n"
            body += (f"theorem zero{d} : ∀ t0 < 24, ∀ t1 < 24, ∀ i2 < List.length {S1d}, ∑ p : PF {LEAN_FAM[fam]}, "
                     f"(Ps.map fun P => P.fac * FTP P (actF p.1 (gpt {S1d} {d} t0 t1 i2))).sum = 0 :=\n"
                     f"  family_at_d_zeroR (f := {LEAN_FAM[fam]}) {BOSN[fam]} {HB[fam]} {HC[fam]} {HN[fam]} {beta} "
                     f"(by norm_num) {S1d} (by decide) {d} (by norm_num) pos{d} mask{d} posok{d} cov{d} Ps Qs{d} rfl "
                     f"stat{d} at{d} hD{d} famz{d}\n")
    partmods = [f"{mp}.P{i}" for i in range(n)]
    if not a.measure_only and not a.grid_only:
        write("K", hdr(ns, [f"{mp}.Orb"] + partmods, cmd) + kb + f"\nend {ns}\n")
    if zero and n and not a.measure_only:
        cases = ""
        for d in DC:
            cases += (f"  · have e : ({S1F[fam]} {d}).map Fin.val = {S1[d]} := by decide\n"
                      f"    rw [e]\n"
                      f"    exact zero{d} t0 ht0 t1 ht1 i2 (by rw [← e, List.length_map]; exact hi2)\n")
        body += (f"\ntheorem hz : ∀ dd ∈ {DCF[fam]}, ∀ t0 < 24, ∀ t1 < 24, ∀ i2 < ({S1F[fam]} dd).length, "
                 f"∑ p : PF {LEAN_FAM[fam]}, (Ps.map fun P => P.fac * FTP P (actF p.1 (gpt (({S1F[fam]} dd).map Fin.val) "
                 f"dd t0 t1 i2))).sum = 0 := by\n"
                 f"  intro dd hdd t0 ht0 t1 ht1 i2 hi2\n"
                 f"  simp only [{DCF[fam]}, List.mem_cons, List.not_mem_nil, or_false] at hdd\n"
                 f"  rcases hdd with {' | '.join(['rfl'] * len(DC))}\n" + cases)
        body += (f"\n/-- **The family's route-2′ zero** (the `FamZero` that `identity_of_decomp` takes). -/\n"
                 f"theorem famZero : LayerDT0.FamZero {LEAN_FAM[fam]} Ps :=\n"
                 f"  LayerDT0.famZero_of_grid Ps {BOSF[fam]} {DCF[fam]} {S1F[fam]} {MEMF[fam]} {MEETS[fam]} hz\n"
                 f"\n#print axioms famZero\n")
        if anyrc:
            body += recompress.lean_os(parts, LEAN_FAM[fam]) + "\n#print axioms famZeroO\n"
        write("Fam", hdr(ns, ["LayerDProto.R2Families", "LayerDProto.R2Reduced", "LayerDT0.IdentityAsm", f"{mp}.K"]
                          + ([recompress.SOUND_IMPORT] if anyrc else []), cmd,
                          "LayerDProto WernerEndpoint") + body + f"\nend {ns}\n")
    if not a.measure_only:
        old = open(a.list).read().splitlines() if os.path.exists(a.list) else [
            "# Lean modules of the IdentityT0 kernel checks, in build order (read by run_identity.sh).",
            "# One module per line; blank lines and lines starting with # are skipped.",
            "# Per family: Pos, Orb, the part modules P<i>, then K (family checks) and Fam (FamZero)."]
        old = [l for l in old if not l.startswith(mp + ".")]
        old.append(f"# family {fam}: {n} parts, generated by gen_totals.py {cmd}")
        if a.grid_only:
            old.append(f"# family {fam}: the part modules P<i>, K and Fam follow once step 1's parts exist "
                       f"(gen_totals.py {fam} --parts step1)")
        with open(a.list, "w") as fh:
            fh.write("\n".join(old + mods) + "\n")
    summ = dict(fam=fam, parts=n, failed=failed, zero=zero, betas=betas, pos={d: len(RG[d]["pos"]) for d in DC},
                grid={d: RG[d]["N"] for d in DC}, bytes=sizes, total_bytes=sum(sizes.values()),
                lit_bytes=sum(s["lit_bytes"] for s in stats),
                full_lit_bytes_est=sum(s["full_lit_bytes_est"] for s in stats), secs=round(time.time() - t0, 1),
                parts_detail=stats)
    with open(os.path.join(out, "summary.json"), "w") as fh:
        json.dump(summ, fh, indent=1)
    print(json.dumps({k: v for k, v in summ.items() if k not in ("parts_detail", "bytes")}))


if __name__ == "__main__":
    main()
