#!/usr/bin/env python3
"""Layer D (t = 0): write LayerDT0/Gen/Sites<cut>.lean, one SiteData per site module and its SiteCert proof.

Untrusted: adjugate, determinant, congruence W, bounds and width beta are computed here and re-checked by the kernel
(LayerDT0.Sites.siteCert_of_chk).  Usage: python3 gen_sites.py [OUT_DIR]   (LAYERD_CERT selects the certificate)
"""
import os, sys
from fractions import Fraction
import t0data as D

OUT = sys.argv[1] if len(sys.argv) > 1 else D.GEN
HDR = "/-! Generated by `layerD_t0/gen_sites.py` from the certificate directory; do not edit by hand. -/\n"


def ptrim(a):
    a = list(a)
    while a and a[-1] == 0:
        a.pop()
    return a


def padd(a, b):
    n = max(len(a), len(b))
    return [(a[i] if i < len(a) else 0) + (b[i] if i < len(b) else 0) for i in range(n)]


def pmul(a, b):
    if not a or not b:
        return []
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return out


def pdet(M):
    k = len(M)
    if k == 1:
        return M[0][0]
    tot = []
    for j in range(k):
        minor = [row[:j] + row[j + 1:] for row in M[1:]]
        term = pmul(M[0][j], pdet(minor))
        tot = padd(tot, term if j % 2 == 0 else [-x for x in term])
    return ptrim(tot)


def padj(M):
    k = len(M)
    if k == 1:
        return [[[1]]]
    out = [[None] * k for _ in range(k)]
    for i in range(k):
        for j in range(k):
            minor = [row[:j] + row[j + 1:] for r, row in enumerate(M) if r != i]
            cof = pdet(minor)
            out[j][i] = ptrim(cof if (i + j) % 2 == 0 else [-x for x in cof])
    return out


def dom_pos(l):
    l = ptrim(l)
    if not l:
        return False
    n = len(l) - 1
    return l[n] > 0 and sum(abs(l[i]) * 4 ** i for i in range(n)) < l[n] * 4 ** n


def el(F0, W, a, b, k):
    out = []
    for t in range(k):
        for u in range(k):
            c = W[a][t] * W[b][u]
            out = padd(out, [c * x for x in F0[t][u]])
    return out


def dom_rows_ok(F0, W, k):
    for a in range(k):
        q = list(el(F0, W, a, a, k))
        for b in range(k):
            if b != a:
                q = padd(q, [-abs(x) for x in el(F0, W, a, b, k)])
        if not dom_pos(q):
            return False
    return True


def ldl_w(F0, k):
    """integer lower-triangular W (positive diagonal) with W F0 W^T diagonal, for constant F0"""
    A = [[Fraction(F0[i][j][0] if F0[i][j] else 0) for j in range(k)] for i in range(k)]
    L = [[Fraction(int(i == j)) for j in range(k)] for i in range(k)]
    Dg = [Fraction(0)] * k
    for j in range(k):
        Dg[j] = A[j][j] - sum(L[j][m] ** 2 * Dg[m] for m in range(j))
        for i in range(j + 1, k):
            L[i][j] = (A[i][j] - sum(L[i][m] * L[j][m] * Dg[m] for m in range(j))) / Dg[j]
    # W = L^{-1} (unit lower triangular), rows scaled to integers
    Wf = [[Fraction(int(i == j)) for j in range(k)] for i in range(k)]
    for i in range(k):
        for j in range(i):
            Wf[i][j] = -sum(L[i][m] * Wf[m][j] for m in range(j, i))
    W = []
    for row in Wf:
        den = 1
        for v in row:
            den = den * v.denominator // __import__("math").gcd(den, v.denominator)
        W.append([int(v * den) for v in row])
    return W


def site_data(T, r, m):
    k, alpha = m["k"], m["alpha"]
    F = [[[ptrim(m["F"][p][i][j]) for j in range(k)] for i in range(k)] for p in range(24)]
    for p in range(24):
        for i in range(k):
            for j in range(k):
                assert all(c.denominator == 1 for c in m["N"][p][i][j]), "N not integral"
    N = [[[ptrim([int(c) for c in m["N"][p][i][j]]) for j in range(k)] for i in range(k)] for p in range(24)]
    Fe = F[D.E_]
    assert D.E_ == 0
    A = padj(Fe)
    dl = pdet(Fe)
    W = [[int(i == j) for j in range(k)] for i in range(k)]
    if not dom_rows_ok(Fe, W, k):
        assert all(len(Fe[i][j]) <= 1 for i in range(k) for j in range(k)), "non-constant F(e) needs a W"
        W = ldl_w(Fe, k)
        assert dom_rows_ok(Fe, W, k)
    assert dom_pos(dl)
    e = alpha + 4
    assert e >= 0
    MF = max([abs(c) for p in F for row in p for l in row for c in l] + [0])
    DF = max(len(l) for p in F for row in p for l in row)
    MA = max([abs(c) for row in A for l in row for c in l] + [0])
    DA = max([len(l) for row in A for l in row] + [0])
    Md, Dd = max([abs(c) for c in dl] + [0]), len(dl)
    MN = max([abs(c) for p in N for row in p for l in row for c in l] + [0])
    assert max(len(l) for p in N for row in p for l in row) <= 7
    Bhom = k * (k * ((DF + DA) * ((DF * (MF * MA)) * MF))) + Dd * (Md * MF)
    Bwg = 24 * MN + 7 * (49 * MF)
    Badj = k * (DF * (MF * MA)) + Md
    beta = (2 * max(Bhom, Bwg, Badj)).bit_length() + 1
    return dict(k=k, F=F, A=A, dl=dl, N=N, e=e, W=W, MF=MF, DF=DF, MA=MA, DA=DA, Md=Md, Dd=Dd, MN=MN, beta=beta)


def rowsplit(name, prop, n=24):
    out = [f"theorem {name}_{i} : {prop.replace('ROW', f'({i} : Fin {n})')} := by\n  decide +kernel\n" for i in range(n)]
    out.append(f"theorem {name} : ∀ i : Fin {n}, {prop.replace('ROW', 'i')} := by\n  intro i; fin_cases i\n  exacts ["
               + ", ".join(f"{name}_{i}" for i in range(n)) + "]\n")
    return "\n".join(out)


def gen_cut(T, mods):
    lean, cname = D.CUT_LEAN[T], D.CUT_NAME[T]
    L = ["import LayerDT0.Sites\nimport LayerDT0.Gen.Tables\n", HDR,
         "\nset_option Elab.async false\nset_option maxRecDepth 100000\n\nnamespace LayerDT0\n\nopen WernerEndpoint\n"]
    names = []
    for r, m in enumerate(mods):
        s = site_data(T, r, m)
        nm = f"{cname}_{r}"
        names.append(nm)
        L.append(f"/-- Site module {r} of cut `{lean}` (`k = {s['k']}`, `α = {s['e'] - 4}`). -/\n"
                 f"def sd_{nm} : SiteData where\n"
                 f"  k := {s['k']}\n  F := {D.lean_list(s['F'])}\n  A := {D.lean_list(s['A'])}\n"
                 f"  δ := {D.lean_list(s['dl'])}\n  N := {D.lean_list(s['N'])}\n  e := {s['e']}\n"
                 f"  W := {D.lean_list(s['W'])}\n  MF := {s['MF']}\n  DF := {s['DF']}\n  MA := {s['MA']}\n"
                 f"  DA := {s['DA']}\n  Md := {s['Md']}\n  Dd := {s['Dd']}\n  MN := {s['MN']}\n  β := {s['beta']}\n")
        for part in ("bndOK", "transOK", "adjOK", "pdOK"):
            L.append(f"theorem {part}_{nm} : sd_{nm}.{part} = true := by\n  decide +kernel\n")
        L.append(rowsplit(f"hom_{nm}", f"sd_{nm}.homRow tabS_{cname} tabL_{cname} ROW = true"))
        L.append(rowsplit(f"wg_{nm}", f"sd_{nm}.wgRow ROW = true"))
        L.append(f"/-- **`SiteCert`** for site module {r} of cut `{lean}`, every `d ≥ 4`. -/\n"
                 f"theorem siteCert_{nm} : SiteCert tab_{cname} (NP sd_{nm}.k sd_{nm}.N) :=\n"
                 f"  siteCert_of_chk bndOK_{nm} transOK_{nm} adjOK_{nm} hom_{nm} wg_{nm} pdOK_{nm}\n")
    L.append("end LayerDT0\n")
    for nm in names:
        L.append(f"#print axioms LayerDT0.siteCert_{nm}\n")
    return "\n".join(L)


def main():
    os.makedirs(OUT, exist_ok=True)
    S, den = D.load_sites()
    assert den == [Fraction(v) for v in (1, 0, -14, 0, 49, 0, -36)]
    only = os.environ.get("LAYERD_CUTS")
    for T, _, cname in D.CUTS:
        if only and cname not in only.split(","):
            continue
        open(os.path.join(OUT, f"Sites{cname}.lean"), "w").write(gen_cut(T, S[T]))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
