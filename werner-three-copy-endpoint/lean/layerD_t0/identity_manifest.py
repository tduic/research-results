#!/usr/bin/env python3
"""Layer D (t = 0): pin the generated (git-ignored) identity modules LayerDT0/Gen/Id/F<f>/*.lean.

identity_manifest.json records, per family, the number of Lean files and one SHA-256 over the sorted lines
"<file> <sha256 of the file>", the SHA-256 of identity_modules.txt and of the generator scripts. Regenerating
(`gen_identity_t0.py FAM`, about 30 min per family; `--reuse` from prep_cache.pkl: 20 s) must reproduce it.
A generated file's first line, the comment `-- GENERATED by <command line>`, is left out of its hash: it records the
generator's arguments (scratch paths among them), carries no Lean content, and differs between machines.

Usage: python3 identity_manifest.py [--write]   (prints OK and exits 0 on success; prints MISMATCH ... and exits 1)
"""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAN = os.path.join(HERE, "identity_manifest.json")
ID = os.path.join(HERE, "LayerDT0", "Gen", "Id")
SCRIPTS = ["gen_identity_t0.py", "identity_parts.py", "gen_totals.py", "../layerD_proto/recompress.py",
           "../layerD_proto/gen_asm.py", "../layerD_proto/route2.py", "../layerD_proto/reduced.py"]


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def lean_sha(p):
    """SHA-256 of a generated Lean file without its first line if that is the `-- GENERATED by ...` comment"""
    b = open(p, "rb").read()
    if b.startswith(b"-- GENERATED by "):
        b = b.split(b"\n", 1)[1] if b"\n" in b else b""
    return hashlib.sha256(b).hexdigest()


def current():
    out = {}
    for f in ("31", "22", "13"):
        d = os.path.join(ID, f"F{f}")
        files = sorted(x for x in os.listdir(d) if x.endswith(".lean")) if os.path.isdir(d) else []
        agg = hashlib.sha256("".join(f"{x} {lean_sha(os.path.join(d, x))}\n" for x in files).encode()).hexdigest()
        out[f"F{f}"] = {"files": len(files), "sha256": agg}
    out["identity_modules.txt"] = sha(os.path.join(HERE, "identity_modules.txt"))
    out["scripts"] = {s: sha(os.path.join(HERE, s)) for s in SCRIPTS}
    return out


def main():
    cur = current()
    if "--write" in sys.argv:
        json.dump(cur, open(MAN, "w"), indent=1, sort_keys=True)
        print("wrote", MAN)
        return
    want = json.load(open(MAN))
    bad = [k for k in sorted(set(cur) | set(want)) if cur.get(k) != want.get(k)]
    print("OK" if not bad else "MISMATCH " + " ".join(bad))
    sys.exit(0 if not bad else 1)


if __name__ == "__main__":
    main()
