"""Rebuild every code from the compact description given in the paper.

Words are strings over {0,1,2}. `G_s` is the group generated by x -> x + (1,...,1) (mod 3)
and the cyclic shift of coordinates by s positions.
"""
import itertools

ORBIT_CODES = {  # n: (shift s, orbit representatives)
    10: (2, ["0001101220", "0012020120"]),
    11: (1, ["00000000000", "00011101201"]),
    12: (2, ["000111222111", "000121012221", "000122201112", "010201020102"]),
}
D16_BASIS = ["0001221202201001", "0110120102221111", "1010100010111101"]
C16_COSET_REPS = ["0000000000000000", "0010011222101021", "0010122101011012", "0020221012102011"]


def _vec(w):
    return tuple(int(c) for c in w)


def _add(u, v):
    return tuple((a + b) % 3 for a, b in zip(u, v))


def orbit(w, s):
    w, n = _vec(w), len(w)
    out = set()
    for k in range(3):
        v = tuple((x + k) % 3 for x in w)
        for r in range(0, n, s):
            out.add(v[r:] + v[:r])
    return out


def orbit_code(n):
    s, reps = ORBIT_CODES[n]
    return set().union(*(orbit(r, s) for r in reps))


def span(basis):
    B = [_vec(b) for b in basis]
    n = len(B[0])
    return {tuple(sum(c * b[i] for c, b in zip(co, B)) % 3 for i in range(n))
            for co in itertools.product(range(3), repeat=len(B))}


def code16():
    D = span(D16_BASIS)
    return {_add(_vec(r), d) for r in C16_COSET_REPS for d in D}


def code17():
    """Kurz, Lemma 1 applied to the n = 16 code with c = 0: {(0,0), (0,1)} U {(c',2) : c' != 0}."""
    C, zero = code16(), (0,) * 16
    return {zero + (0,), zero + (1,)} | {c + (2,) for c in C if c != zero}


def all_codes():
    return {10: orbit_code(10), 11: orbit_code(11), 12: orbit_code(12), 16: code16(), 17: code17()}


if __name__ == "__main__":
    for n, C in all_codes().items():
        print(n, len(C))
